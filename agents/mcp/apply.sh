#!/usr/bin/env bash

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG="$SCRIPT_DIR/servers.json"
CLIENT="${1:-all}"

command -v jq >/dev/null 2>&1 || {
  echo "error: 'jq' not found on PATH (brew install jq)" >&2
  exit 1
}

case "$CLIENT" in
all | claude | opencode | pi) ;;
*)
  echo "usage: $0 [all|claude|opencode|pi]" >&2
  exit 2
  ;;
esac

has_servers() {
  [ "$(jq '.mcpServers // {} | length' "$CONFIG")" -gt 0 ]
}

declared_servers() {
  jq -r '.mcpServers // {} | keys[]' "$CONFIG"
}

apply_pi() {
  # Pi reads a plain JSON file. pi/mcp.json is stowed to ~/.pi/agent/mcp.json,
  # so writing the repo file keeps the live config in sync. Pi rejects the
  # "remote" and "sse" transport types, so drop `type` for those (a `url`
  # selects streamable HTTP on its own). Writing an empty map clears Pi.
  local out="$SCRIPT_DIR/../../pi/mcp.json"
  echo "Applying pi MCP servers -> $out"
  jq '{mcpServers: (.mcpServers // {} | map_values(
        if (.type == "remote" or .type == "sse") then del(.type) else . end))}' \
    "$CONFIG" >"$out"
}

apply_claude() {
  command -v claude >/dev/null 2>&1 || {
    echo "error: 'claude' CLI not found on PATH" >&2
    return 1
  }

  # Claude has no bulk update, so when nothing is declared remove each
  # user-scope server individually.
  if ! has_servers; then
    echo "No MCP servers declared; clearing Claude MCP servers"
    while IFS= read -r name; do
      [ -n "$name" ] || continue
      echo "Removing Claude MCP server: $name"
      claude mcp remove "$name" --scope user
    done < <(jq -r '.mcpServers // {} | keys[]' "$HOME/.claude.json" 2>/dev/null || true)
    return
  fi

  while IFS= read -r name; do
    # Claude's add-json rejects `type: "remote"`/`"sse"` and the `oauth` block
    # (it negotiates OAuth interactively), so normalize before adding.
    config=$(jq -c --arg name "$name" '.mcpServers[$name]
      | if (.type == "remote" or .type == "sse") then .type = "http" else . end
      | del(.oauth)' "$CONFIG")
    echo "Applying Claude MCP server: $name"
    claude mcp remove "$name" --scope user >/dev/null 2>&1 || true
    claude mcp add-json "$name" "$config" --scope user
  done < <(declared_servers)
}

apply_opencode() {
  # opencode.jsonc is hand-written JSONC, which jq cannot parse. Replace only
  # the block between the generated markers so comments and unrelated settings
  # survive. Writing an empty map clears the servers, since opencode has no
  # `mcp remove`.
  local out="$SCRIPT_DIR/../../opencode/opencode.jsonc"
  if [ ! -f "$out" ]; then
    echo "error: $out not found" >&2
    return 1
  fi

  local servers
  servers=$(jq '
    .mcpServers // {}
    | map_values(
        if (.type == "http" or .type == "sse" or .type == "remote"
            or (.type == null and has("url"))) then
          {type: "remote", url: .url}
          + (if has("headers") then {headers: .headers} else {} end)
        else
          {type: "local",
           command: (if (.command | type) == "array" then .command
                     else ([.command] + (.args // [])) end)}
          + (if ((.env // {}) | length) > 0 then {environment: .env} else {} end)
        end)
  ' "$CONFIG")

  local tmp block
  tmp=$(mktemp "${out}.XXXXXX")
  block=$(mktemp "${out}.block.XXXXXX")

  # Render the generated member at the top level, then strip jq's outer braces
  # so it can be inserted directly into the config object.
  {
    printf '  // BEGIN MCP servers (generated by `make agent-mcp`)\n'
    jq -n --argjson servers "$servers" '{mcp: {servers: $servers}}' \
      | sed '1d;$d' \
      | sed '$ s/$/,/'
    printf '  // END MCP servers\n'
  } >"$block"

  if ! awk -v blockfile="$block" '
    BEGIN {
      while ((getline line < blockfile) > 0) block = block line "\n"
      close(blockfile)
    }
    /BEGIN MCP servers/ { found = 1; printf "%s", block; skipping = 1; next }
    skipping && /END MCP servers/ { skipping = 0; next }
    skipping { next }
    { print }
    END { if (!found) exit 3 }
  ' "$out" >"$tmp"; then
    rm -f "$tmp" "$block"
    echo "error: MCP markers not found in $out" >&2
    return 1
  fi

  # mktemp creates the file as 0600; keep the config's existing mode.
  chmod "$(stat -f '%Lp' "$out" 2>/dev/null || stat -c '%a' "$out")" "$tmp"
  mv "$tmp" "$out"
  rm -f "$block"
  echo "Applying opencode MCP servers -> $out"
}

if [ "$CLIENT" = "all" ] || [ "$CLIENT" = "pi" ]; then
  apply_pi
fi

if [ "$CLIENT" = "all" ] || [ "$CLIENT" = "opencode" ]; then
  apply_opencode
fi

if [ "$CLIENT" = "all" ] || [ "$CLIENT" = "claude" ]; then
  apply_claude
fi
